// Generate color overrides for every existing component, preserving layout and media queries.
import fs from 'node:fs/promises';
import postcss from 'postcss';
const root=postcss.parse(await fs.readFile('src/styles.css','utf8'));
function color(hex, property) {
 let h=hex.slice(1); if(h.length===3||h.length===4) h=[...h].map(c=>c+c).join('');
 const rgb=[0,2,4].map(i=>parseInt(h.slice(i,i+2),16)/255);
 const max=Math.max(...rgb),min=Math.min(...rgb),l=(max+min)/2;
 const text=property==='color'||property==='fill'||property==='stroke';
 const border=property.includes('border')||property.includes('shadow')||property.includes('outline');
 let target=text?(l<.72 ? .79 : l):(border ? .29 : l>.45 ? .10+(1-l)*.16 : Math.min(l,.24));
 const spread=max-min; const scale=spread ? Math.min(.13,spread*.35)/spread : 0;
 const mid=(max+min)/2;
 return '#'+rgb.map(c=>Math.round(Math.max(0,Math.min(1,target+(c-mid)*scale))*255).toString(16).padStart(2,'0')).join('')+(h.length===8?h.slice(6):'');
}
const output=postcss.root();
function visit(container,dest){
 for(const node of container.nodes??[]){
  if(node.type==='atrule'){
   if(node.name==='media'&&!node.params.includes('print')){const next=postcss.atRule({name:node.name,params:node.params});visit(node,next);if(next.nodes?.length)dest.append(next);}
  } else if(node.type==='rule'){
   const rule=postcss.rule({selector:node.selectors.map(s=>s.trim()===':root'?'html[data-theme="dark"]':'html[data-theme="dark"] '+s).join(',\n')});
   for(const d of node.nodes??[]){if(d.type!=='decl'||(!d.value.includes('#')&&!/^(color|background|border|fill|stroke)/.test(d.prop)))continue;
    if(!d.value.includes('#')&&!/\b(white|black)\b/.test(d.value))continue;
    let value=d.value.replace(/\bwhite\b/g,'#ffffff').replace(/\bblack\b/g,'#000000').replace(/#[\da-f]{3,8}\b/gi,h=>color(h,d.prop));
    rule.append(d.clone({value}));
   }if(rule.nodes?.length)dest.append(rule);
  }
 }
}
visit(root,output);
await fs.writeFile('src/dark.css','/* Generated by scripts/build-dark-theme.mjs. Screen-only: print stays light. */\n@media screen {\n'+output.toString()+'\nhtml[data-theme="dark"] { color-scheme: dark; --dark:#e0ece5; --muted:#b1c0b7; --line:#3b5147; --cream:#19241e; --green:#92c7a9; --amber:#e0b775; }\nhtml[data-theme="dark"] .button.primary, html[data-theme="dark"] .replay-step.current .replay-step-icon { background:#315a46; color:#fff; }\nhtml[data-theme="dark"] .button.light { color:#e0ece5; background:#294437; }\n}\n');
