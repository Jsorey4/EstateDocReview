"""Generate frontend vocabulary directly from the backend's authoritative schema."""
import json
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from edr.schema import FIELDS, DOCUMENT_TYPES
from edr.issues import ISSUE_TYPES


def source():
    return '// Generated by scripts/sync_backend_contract.py; do not edit by hand.\n' + '\n'.join(
        f'export const {name} = {json.dumps(list(values))} as const;'
        for name, values in [('BACKEND_FIELDS', FIELDS), ('BACKEND_DOCUMENT_TYPES', DOCUMENT_TYPES), ('BACKEND_ISSUE_TYPES', ISSUE_TYPES)]
    ) + '\n'


if __name__ == '__main__':
    target = Path(__file__).resolve().parents[1] / 'src/backendContract.ts'
    if '--check' in sys.argv:
        if target.read_text() != source():
            raise SystemExit('Frontend vocabulary is stale; run python3 scripts/sync_backend_contract.py')
    else:
        target.write_text(source())
